import { expect, test } from '@playwright/test'

test('inbox supports search and unread filtering with one profile batch', async ({ page }, info) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/?screen=inbox')
  await expect(page.locator('.inbox-conversation')).toHaveCount(1)
  await page.getByRole('button', { name: 'Unread', exact: true }).click()
  await expect(page.locator('.inbox-conversation')).toHaveCount(1)
  await page.getByRole('textbox', { name: 'Search loaded conversations' }).fill('nobodymatches')
  await expect(page.getByText('No matching chats')).toBeVisible()
  await page.getByRole('textbox', { name: 'Search loaded conversations' }).fill('creator')
  await expect(page.locator('.inbox-conversation')).toHaveCount(1)
  expect(await page.evaluate(() => (window as unknown as { __queries: string[] }).__queries.filter(t => t === 'profiles').length)).toBeLessThanOrEqual(2)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('inbox-redesign.png'), fullPage: true })
  expect(errors).toEqual([])
})

test('chat fits long text and a multiline composer, sends and exposes actions', async ({ page }, info) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/?screen=chat')
  await expect(page.getByText('Absolutely! See you there ✨')).toBeVisible()
  const input = page.getByRole('textbox', { name: 'Message', exact: true })
  await input.fill('First line\nSecond line\nThird line')
  const composer = await page.locator('.chat-composer').boundingBox()
  const timeline = await page.locator('.chat-timeline').boundingBox()
  expect(composer && timeline && timeline.y + timeline.height <= composer.y + 1).toBeTruthy()
  expect(await page.evaluate(() => [...document.querySelectorAll('.chat-header,.chat-timeline,.chat-composer')].every(el => el.scrollWidth <= el.clientWidth + 1))).toBe(true)
  await page.screenshot({ path: info.outputPath('chat-redesign.png') })
  await page.getByRole('button', { name: 'Send message', exact: true }).click()
  await expect(input).toHaveValue('')
  await expect(page.locator('.chat-bubble').filter({ hasText: 'Third line' })).toHaveCount(1)
  await page.getByRole('button', { name: 'Message actions' }).last().click()
  await expect(page.getByRole('button', { name: 'Reply', exact: true })).toBeVisible()
  await page.emulateMedia({ colorScheme: 'light' })
  await page.getByRole('button', { name: 'Reply', exact: true }).click()
  await page.screenshot({ path: info.outputPath('chat-light.png') })
  expect(errors).toEqual([])
})

test('post body and photo open the post, author links retain profile navigation', async ({ page }) => {
  await page.goto('/?screen=feed')
  const article = page.locator('article[aria-label^="Open post by"]').first()
  await expect(article).toBeVisible()
  await expect(article.locator('a[href="/profile/creator"]').first()).toBeVisible()
  await article.locator('.post-text').click()
  expect(await page.evaluate(() => (window as unknown as { __navigation: string }).__navigation)).toBe('/posts/1')
  await page.evaluate(() => { (window as unknown as { __navigation: string }).__navigation = '' })
  await article.getByRole('link', { name: 'Open post media 1' }).click()
  expect(await page.evaluate(() => (window as unknown as { __navigation: string }).__navigation)).toBe('/posts/1')
  await expect(page.locator('article[aria-label^="Open post by"] video').first()).toHaveAttribute('preload', 'none')
})
